import type { Mode } from './theory'

/**
 * Характер перехода:
 * - home  — приход к тонике, разрешение
 * - lift  — рост напряжения, ожидание
 * - drift — мягкое, плавное движение
 * - turn  — неожиданный или острый поворот
 * - stay  — остаёмся на месте
 */
export type Kind = 'home' | 'lift' | 'drift' | 'turn' | 'stay'

export interface Transition {
  kind: Kind
  /** Короткое название ощущения (в ячейке) */
  label: string
  /** Пояснение (в панели под таблицей) */
  text: string
}

export const KINDS: Record<Kind, { name: string; hint: string }> = {
  home: { name: 'Возвращение', hint: 'приход к тонике, облегчение' },
  lift: { name: 'Напряжение', hint: 'ожидание, хочется продолжения' },
  drift: { name: 'Плавный ход', hint: 'мягкое, спокойное движение' },
  turn: { name: 'Поворот', hint: 'острый или неожиданный ход' },
  stay: { name: 'На месте', hint: 'тот же аккорд' },
}

type Raw = readonly [kind: string, label: string, text: string]

const KIND_BY_CODE: Record<string, Kind> = {
  h: 'home',
  l: 'lift',
  d: 'drift',
  t: 'turn',
  s: 'stay',
}

const decode = ([code, label, text]: Raw): Transition => ({
  kind: KIND_BY_CODE[code]!,
  label,
  text,
})

